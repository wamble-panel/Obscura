export const dictionaries: Record<Lang, Record<DictKey, string>> = { en, ar }

export type Translator = (key: DictKey | string, fallback?: string) => string

export function makeTranslator(lang: Lang): Translator {
  const dict = dictionaries[lang] ?? dictionaries.en
  return (key, fallback) =>
    (dict as Record<string, string>)[key] ??
    (dictionaries.en as Record<string, string>)[key] ??
    fallback ??
    String(key)
}

export function dirFor(lang: Lang): 'ltr' | 'rtl' {
  return lang === 'ar' ? 'rtl' : 'ltr'
}

